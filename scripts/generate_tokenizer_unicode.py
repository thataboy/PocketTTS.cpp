#!/usr/bin/env python3
"""Generate the tokenizer's locale-independent Unicode text-preparation tables.

Run with Python 3.12 (Unicode 15.0), matching the upstream validation environment.
The generated header is committed; Python is not part of the C++ build.
"""
from pathlib import Path
import unicodedata


def ranges(points):
    result = []
    for point in points:
        if result and point == result[-1][1] + 1:
            result[-1][1] = point
        else:
            result.append([point, point])
    return result


def main():
    if unicodedata.unidata_version != '15.0.0':
        raise RuntimeError('Regenerate with Python 3.12 / Unicode 15.0.0')
    lines = ['// Generated by scripts/generate_tokenizer_unicode.py; Unicode 15.0.0.',
             '#pragma once', '#include <cstdint>', 'namespace pocket_text {',
             'struct UnicodeRange { uint32_t first, last; };']
    for name, predicate in [('spaces', str.isspace), ('digits', str.isdigit)]:
        lines.append(f'inline constexpr UnicodeRange {name}[] = {{')
        lines.extend(f'    {{0x{a:X}, 0x{b:X}}},' for a, b in ranges(
            i for i in range(0x110000) if predicate(chr(i))))
        lines.append('};')
    lines += ['struct Uppercase { uint32_t code; const char* text; };',
              'inline constexpr Uppercase uppercase[] = {']
    for i in range(0x110000):
        c = chr(i)
        if not c.isupper() and c.upper() != c:
            text = ''.join(f'\\x{b:02X}' for b in c.upper().encode())
            lines.append(f'    {{0x{i:X}, "{text}"}},')
    lines += ['};', '} // namespace pocket_text', '']
    target = Path(__file__).resolve().parents[1] / 'native_tokenizer/unicode_data.hpp'
    target.write_text('\n'.join(lines))
    print(target)


if __name__ == '__main__':
    main()
